'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const load=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const catalog=load('image-library49.json').assets;
const ledger=load('artwork-review-ledger115d.json');
const handoff=load('native-candidate-handoff115d.json');
const staging=load('artwork-staging115d/manifest.json').assets;
const queue=load('branding-correction-queue115.json').items;
const prior=load('owner-image-review115d.json').reviews;
const approved=new Set(handoff.assets.filter(a=>a.ownerApproval?.status==='approved-by-owner').map(a=>a.id));
const preferred=['veldio104d-fcgroningen-night-preview','veldio75-feyenoord-report','veldio74-fctwente-report'];
const pending=ledger.items.filter(a=>!['manual-pass','already-rejected'].includes(a.status)&&!approved.has(a.id));
const rank=id=>{const i=preferred.indexOf(id);return i<0?99:i};
pending.sort((a,b)=>rank(a.id)-rank(b.id));
const dest=path.join(root,'owner-review-site');
fs.mkdirSync(path.join(dest,'images'),{recursive:true});
const rows=pending.map((l,i)=>{
 const a=catalog.find(x=>x.id===l.id),q=queue.find(x=>x.id===l.id);
 if(!a)throw Error('Missing '+l.id);
 const c=staging.find(x=>x.id===l.id&&x.originalSha256===a.sha256);
 const file=c?.file||a.file,expected=c?.sha256||a.sha256;
 if(!/^([a-zA-Z0-9_-]+\/)+[a-zA-Z0-9_.-]+\.(webp|png|jpg|jpeg)$/i.test(file))throw Error('Invalid image path '+file);
 const bytes=fs.readFileSync(path.join(root,file));
 if(hash(bytes)!==expected)throw Error('Hash mismatch: '+l.id);
 const name=expected+'.'+file.split('.').pop().toLowerCase();
 fs.writeFileSync(path.join(dest,'images',name),bytes);
 const v=prior.find(x=>x.id===a.id&&x.assetSha256===expected&&x.path===file);
 return {number:i+1,id:a.id,title:a.subject,sha256:expected,path:file,image:'images/'+name,kind:c?'Gecorrigeerde kandidaat':q?.technicalReview115?'Resolutie nog onvoldoende':'Huidig beeld',defect:q?.defect||'',initialVote:['JA','NEE'].includes(v?.ownerVote)?v.ownerVote:null};
});
if(new Set(rows.map(x=>x.id)).size!==rows.length)throw Error('Duplicate review ID');
const data=JSON.stringify({rows,version:1}).replace(/</g,'\\u003c');
const template=fs.readFileSync(path.join(root,'public/owner-review115d.html'),'utf8');
if(!template.includes('/* REVIEW_DATA */'))throw Error('Missing data marker');
fs.writeFileSync(path.join(dest,'index.html'),template.replace('/* REVIEW_DATA */',()=> 'const DATA='+data+';'));
console.log('Exported '+rows.length+' exact image files; '+rows.filter(r=>r.initialVote).length+' earlier decisions restored. No publication changes.');
